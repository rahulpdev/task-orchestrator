import esbuild from 'esbuild';
import { mkdir, writeFile } from 'node:fs/promises';
import { builtinModules } from 'node:module';
import path from 'node:path';
import process from 'node:process';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const repositoryRoot = path.resolve(import.meta.dirname, '../..');
const prod = process.argv[2] === 'production';

// Development only: after each successful rebuild, copy the plugin files into the development
// vault. The copy logic is loaded lazily so the production build never loads a .ts file.
const copyToDevVaultPlugin = {
	name: 'copy-to-dev-vault',
	setup(build) {
		build.onEnd(async (result) => {
			if (result.errors.length > 0) {
				return;
			}
			const { copyToDevVault } = await import('../../scripts/copy-to-dev-vault.ts');
			await copyToDevVault(repositoryRoot);
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	absWorkingDir: repositoryRoot,
	entryPoints: [path.resolve(import.meta.dirname, 'src/main.ts')],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
		...builtinModules.map((moduleName) => `node:${moduleName}`),
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: path.resolve(repositoryRoot, 'main.js'),
	minify: prod,
	metafile: prod,
	plugins: prod ? [] : [copyToDevVaultPlugin],
});

if (prod) {
	const result = await context.rebuild();
	const distFolder = path.resolve(repositoryRoot, 'dist');
	await mkdir(distFolder, { recursive: true });
	await writeFile(path.join(distFolder, 'esbuild-meta.json'), JSON.stringify(result.metafile));
	await context.dispose();
	process.exit(0);
} else {
	await context.watch();
}
